#!/usr/bin/env python3
"""Regenerate BRANCH-INDEX.md from brain/changelog/CHANGELOG.md (no manual edits)."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CHANGELOG = ROOT / "brain" / "changelog" / "CHANGELOG.md"
OUT = ROOT / "brain" / "changelog" / "BRANCH-INDEX.md"

ROW = re.compile(
    r"^##\s+(?P<date>\d{4}-\d{2}-\d{2})\s*\|\s*"
    r"(?P<scope>[^|]+)\s*\|\s*"
    r"(?P<service>[^|]+)\s*\|\s*"
    r"(?P<branch>[^|]+)\s*\|\s*"
    r"(?P<tag>[^|]+)\s*\|\s*"
    r"(?P<title>.+)$"
)


def main() -> int:
    if not CHANGELOG.is_file():
        print(f"missing {CHANGELOG}", flush=True)
        return 1
    rows: list[dict[str, str]] = []
    for line in CHANGELOG.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line.strip())
        if not m:
            continue
        d = m.groupdict()
        sha_m = re.search(r"`?([0-9a-f]{7,40})`?", d["scope"])
        d["sha"] = sha_m.group(1) if sha_m else d["scope"].strip()
        rows.append(d)

    by_branch: dict[str, list[dict[str, str]]] = {}
    for r in rows:
        by_branch.setdefault(r["branch"].strip(), []).append(r)

    lines = [
        "# Branch index (auto-generated — do not edit)",
        "",
        "Source: [`CHANGELOG.md`](CHANGELOG.md). Regenerated by `refresh_branch_index.py` on each `changelog-add.sh`.",
        "",
        "Use: find what shipped on **your branch** before KG enrich or reference-doc update.",
        "",
        "| Branch | Latest | Service | Sha | Tag |",
        "|--------|--------|---------|-----|-----|",
    ]
    for branch in sorted(by_branch, key=lambda b: by_branch[b][0]["date"], reverse=True):
        latest = by_branch[branch][0]
        lines.append(
            f"| `{branch}` | {latest['date']} | {latest['service'].strip()} | `{latest['sha'][:10]}` | {latest['tag'].strip()} |"
        )

    lines += ["", "## kg-flow by branch (for KG / reference enrichment)", ""]
    for branch in sorted(by_branch):
        kg = [r for r in by_branch[branch] if "kg-flow" in r["tag"].lower()]
        if not kg:
            continue
        lines.append(f"### `{branch}`")
        for r in kg[:12]:
            lines.append(f"- {r['date']} `{r['sha'][:10]}` — {r['title'].strip()}")
        lines.append("")

    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"[branch-index] {len(rows)} entries → {OUT}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
