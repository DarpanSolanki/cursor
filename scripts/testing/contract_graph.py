#!/usr/bin/env python3
"""
Contract graph — scan orchestration XML + MessageBroker across all microservices.
Exports contracts.jsonl, syncs FTG, links precedents from changelog.

  contract_graph.py scan [--json]
  contract_graph.py stats
  contract_graph.py list [--money] [--protocol HTTP_INTERNAL|KAFKA]
  contract_graph.py show <contract-id>
  contract_graph.py gaps          # money contracts without FTG / tests
  contract_graph.py sync-ftg      # auto-link FTG ids + suggest new rows
  contract_graph.py precedents    # changelog → contract mapping
"""

